def test_actioned_dedupe_repairs_same_bucket_before_strict_index(
    tmp_path: Path,
) -> None:
    owner_root = tmp_path / "repo"
    fingerprint = "1111111111111111"
    complete = owner_root / ".agents" / "plans" / "5 - complete"
    first = complete / f"20260708_{fingerprint}_older-copy.md"
    second = complete / f"20260709_{fingerprint}_newer-copy.md"
    _write_generated_plan(first, fingerprint, "Older generated copy")
    _write_generated_plan(second, fingerprint, "Newer generated copy")

    with pytest.raises(ValueError, match="plan_index_multiple_canonical_copies"):
        scan_plan_ticket_index(owner_root=owner_root)

    assert dedupe_actioned_plan_ticket_files(owner_root=owner_root) == 1
    assert not first.exists()
    assert second.exists()
    index = scan_plan_ticket_index(owner_root=owner_root)
    assert index[fingerprint]["paths"] == [str(second)]
    assert len(index[fingerprint]["relationship_paths"]) == 1

    # Relationship copies are excluded from the raw repair candidate set, so
    # rerunning the repair is byte- and path-stable.
    before = {
        path: path.read_bytes()
        for path in (owner_root / ".agents" / "plans").rglob("*")
        if path.is_file()
    }
    assert dedupe_actioned_plan_ticket_files(owner_root=owner_root) == 0
    after = {
        path: path.read_bytes()
        for path in (owner_root / ".agents" / "plans").rglob("*")
        if path.is_file()
    }
    assert after == before


