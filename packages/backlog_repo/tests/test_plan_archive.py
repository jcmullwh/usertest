    assert outcome is not None
    assert outcome["state"] == "duplicate"
    assert outcome["related_case_id"] == "case:archive-test"
    assert outcome["related_fingerprint"] == fingerprint

    index = scan_plan_ticket_index(owner_root=owner_root)
    assert index[fingerprint]["paths"] == [str(completed)]
    assert index[fingerprint]["relationship_paths"] == [str(archived)]


