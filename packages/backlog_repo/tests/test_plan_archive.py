def _write_plan(path: Path, fingerprint: str, title: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"# {title}\n\n"
        f"- Fingerprint: `{fingerprint}`\n"
        "- Case ID: `case:archive-test`\n"
        "- Plan revision ID: `plan:archive-test:v1`\n",
        encoding="utf-8",
    )


def _write_generated_plan(path: Path, fingerprint: str, title: str) -> None:
    _write_plan(path, fingerprint, title)
    path.write_text(
        path.read_text(encoding="utf-8")
        + "\nGenerated by `python -m usertest_backlog.cli reports export-tickets`.\n",
        encoding="utf-8",
    )


def _passed(
    kind: str,
    reference: str,
    *,
    case_id: str,
    plan_revision_id: str,
    fingerprint: str,
) -> dict[str, object]:
    common = {
        "producer": "usertest_implement",
        "verification_producer": "runner_core",
        "evidence_kind": kind,
        "ticket_body_sha256": "c" * 64,
        "local_plan_sha256": "d" * 64,
        "local_plan_filename": "ticket.md",
        "verification_contract_sha256": "e" * 64,
        "target_contract_sha256": "1" * 64,
        "verified_implementation_head": "2" * 40,
        "fingerprint": fingerprint,
        "case_id": case_id,
        "plan_revision_id": plan_revision_id,
    }
    if kind == "test":
        receipt = {
            **common,
            "receipt_schema_version": 2,
            "run_dir": f"runs/{kind}",
            "verification_path": f"runs/{kind}/verification.json",
            "verification_sha256": "a" * 64,
            "ticket_ref_path": f"runs/{kind}/ticket_ref.json",
            "ticket_ref_sha256": "b" * 64,
            "verification_binding_sha256": "f" * 64,
            "commands": [f"verify-{kind}"],
        }
    else:
        receipt = {
            **common,
            "receipt_schema_version": 3,
            "role_artifact_path": f"runs/{kind}/outcome_role.json",
            "role_artifact_sha256": "a" * 64,
            "role_contract_sha256": "f" * 64,
            "merged_commit": "abc123",
        }
    return {
        "kind": kind,
        "reference": reference,
        "result": "passed",
        "runner_receipt": receipt,
    }


def test_queue_dedupe_archives_relationship_without_losing_plan(tmp_path: Path) -> None:
    owner_root = tmp_path / "repo"
    fingerprint = "0123456789abcdef"
    name = f"20260709_{fingerprint}_archive-test.md"
    queued = owner_root / ".agents" / "plans" / "2 - ready" / name
    completed = owner_root / ".agents" / "plans" / "5 - complete" / name
