def test_ticket_index_and_move(tmp_path: Path) -> None:
    owner_root = tmp_path / "repo"
    ready_dir = owner_root / ".agents" / "plans" / "2 - ready"
    in_progress_dir = owner_root / ".agents" / "plans" / "3 - in_progress"
    ready_dir.mkdir(parents=True)
    in_progress_dir.mkdir(parents=True)

    fingerprint = "deadbeefdeadbeef"
    ticket_path = ready_dir / f"20260220_{fingerprint}_fix-something.md"
    ticket_path.write_text(
        "# Fix something\n\n"
        "- Export kind: `implementation`\n"
        "- Stage: `ready_for_ticket`\n"
        "- Fingerprint: `deadbeefdeadbeef`\n",
        encoding="utf-8",
    )

    index = build_ticket_index(owner_root=owner_root)
    assert fingerprint in index

    selected = select_next_ticket_path(
        index,
        bucket_priority=["2 - ready"],
        kind_priority=["research", "implementation"],
    )
    assert selected is not None
    entry, _ = selected
    assert entry.fingerprint == fingerprint

    dest_dry = move_ticket_file(
        owner_root=owner_root,
        fingerprint=fingerprint,
        to_bucket="3 - in_progress",
        dry_run=True,
    )
    assert dest_dry == in_progress_dir / ticket_path.name
    assert ticket_path.exists()

    dest = move_ticket_file(
        owner_root=owner_root,
        fingerprint=fingerprint,
        to_bucket="3 - in_progress",
        dry_run=False,
    )
    assert dest.exists()
    assert not ticket_path.exists()


def test_ticket_index_repairs_generated_same_bucket_duplicates_first(
    tmp_path: Path,
) -> None:
    owner_root = tmp_path / "repo"
    complete = owner_root / ".agents" / "plans" / "5 - complete"
    complete.mkdir(parents=True)
    fingerprint = "abababababababab"
    marker = "Generated by `python -m usertest_backlog.cli reports export-tickets`."
    older = complete / f"20260708_{fingerprint}_older.md"
    newer = complete / f"20260709_{fingerprint}_newer.md"
    for path, title in ((older, "Older"), (newer, "Newer")):
        path.write_text(
            f"# {title}\n\n{marker}\n\n- Fingerprint: `{fingerprint}`\n",
            encoding="utf-8",
        )

    index = build_ticket_index(owner_root=owner_root)

    assert index[fingerprint].paths == [newer]
    assert not older.exists()
    archived = list((owner_root / ".agents" / "plans" / "6 - archived").glob("*.md"))
    assert len(archived) == 1
    assert "backlog-outcome:start" in archived[0].read_text(encoding="utf-8")


