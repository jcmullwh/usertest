def test_move_to_complete_requires_durable_outcome_record(tmp_path: Path) -> None:
    owner_root = tmp_path / "repo"
    for_review_dir = owner_root / ".agents" / "plans" / "4 - for_review"
    complete_dir = owner_root / ".agents" / "plans" / "5 - complete"
    for_review_dir.mkdir(parents=True)
    complete_dir.mkdir(parents=True)
    fingerprint = "0123456789abcdef"
    ticket_path = for_review_dir / f"20260220_{fingerprint}_verified-change.md"
    ticket_path.write_text(
        "# Verified change\n\n"
        f"- Fingerprint: `{fingerprint}`\n"
        "- Case ID: `case:verified-change`\n"
        "- Plan revision ID: `plan:verified-change:v1`\n",
        encoding="utf-8",
    )

    with pytest.raises(ValueError, match="outcome record"):
        move_ticket_file(
            owner_root=owner_root,
            fingerprint=fingerprint,
            to_bucket="5 - complete",
            dry_run=False,
        )

    outcome = {
        "schema_version": 1,
        "case_id": "case:verified-change",
        "plan_revision_id": "plan:verified-change:v1",
        "state": "tests_verified",
        "recorded_at": "2026-07-09T00:00:00Z",
        "requires_live_verification": False,
        "target_branch": "dev",
        "merged_commit": "abc123",
        "test_evidence": [_passed("test", "tests/test_change.py")],
        "original_scenario_evidence": [],
        "live_evidence": [],
        "remaining_risks": ["Original scenario replay pending"],
        "recurrence_check": {"status": "not_run"},
    }
    completed = move_ticket_file(
        owner_root=owner_root,
        fingerprint=fingerprint,
        to_bucket="5 - complete",
        dry_run=False,
        outcome_record=outcome,
    )

    assert completed.parent == complete_dir
    assert '"state": "tests_verified"' in completed.read_text(encoding="utf-8")

    resolved = transition_outcome_record(
        outcome,
        state="resolved",
        recorded_at="2026-07-10T00:00:00Z",
        updates={
            "original_scenario_evidence": [_passed("original_scenario", "runs/replay")],
            "remaining_risks": [],
            "recurrence_check": {
                "status": "completed",
                "result": "passed",
                "evidence": [_passed("recurrence", "runs/recurrence")],
            },
        },
    )
    completed.write_text(
        upsert_outcome_markdown(completed.read_text(encoding="utf-8"), resolved),
        encoding="utf-8",
    )
    move_ticket_file(
        owner_root=owner_root,
        fingerprint=fingerprint,
        to_bucket="5 - complete",
        dry_run=False,
        outcome_record=outcome,
    )
    persisted = extract_outcome_markdown(completed.read_text(encoding="utf-8"))
    assert persisted is not None
    assert persisted["state"] == "resolved"


