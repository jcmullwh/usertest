def test_clean_worktree_uses_exact_merged_commit_and_removes_it(tmp_path: Path) -> None:
    repository = tmp_path / "repo"
    repository.mkdir()
    subprocess.run(["git", "init"], cwd=repository, check=True, capture_output=True)
    subprocess.run(
        ["git", "config", "user.email", "tests@example.com"],
        cwd=repository,
        check=True,
    )
    subprocess.run(
        ["git", "config", "user.name", "Tests"], cwd=repository, check=True
    )
    (repository / "probe.txt").write_text("merged behavior\n", encoding="utf-8")
    subprocess.run(["git", "add", "probe.txt"], cwd=repository, check=True)
    subprocess.run(["git", "commit", "-m", "merged"], cwd=repository, check=True)
    commit = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=repository,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    root = tmp_path / "controlled-worktrees"

    with progression.clean_merged_commit_worktree(
        repository=repository,
        merged_commit=commit,
        worktrees_root=root,
        fingerprint="0123456789abcdef",
    ) as workspace:
        assert subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=workspace,
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip() == commit
        # A failed oracle may leave an unexpected path outside its staged overlay.
        # The controlled detached worktree is still destroyed in the context cleanup;
        # no dirty evidence workspace is reused by a later role.
        (workspace / "unexpected-oracle-write.txt").write_text(
            "dirty\n",
            encoding="utf-8",
        )
        created_workspace = workspace

    assert not created_workspace.exists()


def test_refresh_continues_unrelated_work_when_merged_outcome_is_unverified(
    tmp_path: Path,
) -> None:
    owner_root = tmp_path / "owner"
    owner_root.mkdir()
    request = BacklogRefreshRequest(
        repo_root=tmp_path,
        repo_input=str(owner_root),
        runs_dir=tmp_path / "runs",
        target="target",
        backlog_python=tmp_path / "python",
    )
    result = progression.OutcomeProgressionResult(
        fingerprint="0123456789abcdef",
        ticket_path=owner_root / "plan.md",
        starting_state="tests_verified",
        final_state="unverified",
        expected_state="resolved",
        status="blocked",
        detail="original scenario still fails",
    )
    executed: list[str] = []

    class RefreshContinued(RuntimeError):
        pass

    def execute(_argv: list[str], _cwd: Path, label: str) -> None:
        executed.append(label)
        raise RefreshContinued

    with pytest.raises(RefreshContinued):
        run_shadow_backlog_refresh(
            request,
            command_executor=execute,
            open_pr_probe=lambda _request: [],
            outcome_progressor=lambda **_: [result],
        )

    assert executed == ["operational shadow materialization"]


