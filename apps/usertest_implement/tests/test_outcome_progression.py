def _install_progression_fakes(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
    *,
    expected_state: str,
    requires_live: bool,
    failing_role: str | None = None,
) -> tuple[dict[str, object], list[str], Path]:
    ticket_path = tmp_path / ".agents" / "plans" / "5 - complete" / "plan.md"
    selected = SimpleNamespace(
        fingerprint="0123456789abcdef",
        ticket_markdown=_plan_markdown(
            expected_state,
            requires_live=requires_live,
        ),
    )
    state: dict[str, object] = {
        "state": "tests_verified",
        "case_id": "case:one",
        "plan_revision_id": "plan:one:v1",
        "merged_commit": "a" * 40,
        "requires_live_verification": requires_live,
        "test_evidence": [{"result": "passed"}],
        "original_scenario_evidence": [],
        "live_evidence": [],
        "mitigation_evidence": [],
        "remaining_risks": [
            "Original failure scenario has not been replayed after merge",
            *(["Live runtime verification is still required"] if requires_live else []),
        ],
        "recurrence_check": {"status": "not_run"},
    }
    roles: list[str] = []

    monkeypatch.setattr(
        progression,
        "_select_review_ticket",
        lambda **_: selected,
    )
    monkeypatch.setattr(progression, "is_generated_backlog_ticket", lambda _: True)
    monkeypatch.setattr(
        progression,
        "_selected_ticket_provenance",
        lambda *_args, **_kwargs: {
            "verification_contract": {
                "outcome_roles": {
                    "original_scenario": {"role_contract_sha256": "d" * 64},
                    "live": (
                        {"role_contract_sha256": "e" * 64}
                        if requires_live
                        else None
                    ),
                    "mitigation_effect": (
                        {"role_contract_sha256": "f" * 64}
                        if expected_state == "mitigated"
                        else None
                    ),
                }
            },
            "verification_contract_sha256": "b" * 64,
            "target_contract_sha256": "c" * 64,
        },
    )
    monkeypatch.setattr(progression, "_load_current", lambda _path: dict(state))
    current_state = state

    def _fake_transition(*, state: str, updates: dict[str, object], **_kwargs):
        current_state.update(updates)
        current_state["state"] = state
        return dict(current_state)

    monkeypatch.setattr(progression, "_transition", _fake_transition)
    # These tests isolate role selection and state movement. Terminal provenance
    # itself has dedicated coverage below, including the newly-terminal call site.
    monkeypatch.setattr(
        progression,
        "_require_terminal_outcome_provenance",
        lambda **_: None,
    )

    @contextmanager
    def _fake_worktree(**_kwargs):
        yield tmp_path

    monkeypatch.setattr(progression, "clean_merged_commit_worktree", _fake_worktree)

    def _fake_run_role(*, role: str, output_path: Path, **_kwargs):
        roles.append(role)
        if role == failing_role:
            raise progression.OutcomeRoleDidNotPass(
                role=role,
                artifact_path=output_path,
                timed_out=False,
            )
        return {
            "kind": "runner_outcome_role",
            "reference": str(output_path),
            "result": "passed",
        }

    monkeypatch.setattr(progression, "_run_role", _fake_run_role)
    return state, roles, ticket_path


