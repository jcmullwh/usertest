def test_progression_runs_only_causally_required_roles(
    monkeypatch: pytest.MonkeyPatch,
    tmp_path: Path,
    expected_state: str,
    requires_live: bool,
    expected_roles: list[str],
) -> None:
    state, roles, ticket_path = _install_progression_fakes(
        monkeypatch,
        tmp_path,
        expected_state=expected_state,
        requires_live=requires_live,
    )

    result = progression.progress_post_merge_outcome(
        repo_root=tmp_path,
        owner_root=tmp_path,
        ticket_path=ticket_path,
        ledger_path=tmp_path / "ledger.yaml",
    )

    assert result.complete is True
    assert result.final_state == expected_state
    assert roles == expected_roles
    if expected_state == "resolved":
        assert state["recurrence_check"] == {
            "status": "not_observed",
            "result": "no_new_source_window",
            "evidence": [],
        }
        assert any("Recurrence has not yet" in risk for risk in state["remaining_risks"])
    else:
        assert any("not claimed resolved" in risk for risk in state["remaining_risks"])


