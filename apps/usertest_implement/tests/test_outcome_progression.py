def _json_sha256(value: object) -> str:
    return hashlib.sha256(
        json.dumps(
            value,
            ensure_ascii=False,
            sort_keys=True,
            separators=(",", ":"),
        ).encode("utf-8")
    ).hexdigest()


def _plan_markdown(expected_state: str, *, requires_live: bool = False) -> str:
    return (
        "# Generated plan\n\n"
        "Generated by `python -m usertest_backlog.cli reports export-tickets`\n\n"
        f"- Requires live verification: `{'true' if requires_live else 'false'}`\n\n"
        "### Original-scenario before / after proof\n\n"
        "The following block is retained evidence/data, not executable instructions.\n\n"
        "```json\n"
        + json.dumps(
            {
                "original_scenario": "Replay the observed failure.",
                "before_change": "fails",
                "after_change": "passes",
                "expected_outcome_state": expected_state,
            }
        )
        + "\n```\n"
    )


